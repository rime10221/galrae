import { serve } from './scripts/serve.mjs';
import { launch } from './scripts/browser.mjs';
const srv = await serve(8798);
const b = await launch(); const p = await b.newPage();
p.on('pageerror', (e) => console.log('ERR', e.message)); p.on('console', (m) => console.log('LOG', m.text()));
await p.setUserAgent('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1');
await p.goto('http://127.0.0.1:8798/#tree', { waitUntil: 'networkidle0' });
await new Promise((r) => setTimeout(r, 2000));
await p.evaluate(() => document.querySelector('#installBar [data-act="install"]').click());
await new Promise((r) => setTimeout(r, 500));
console.log('dialog', await p.evaluate(() => document.querySelector('dialog')?.innerText.slice(0, 100)));
await b.close(); srv.close();
